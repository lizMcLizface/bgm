// Literal scalar Float32 stages and explicitly fused operations. Tables are
// immutable source constants, not measured/fitted PCM. No CPU/rate dispatch.
pub(crate) fn log10f(x: f32) -> f32 {
    if x.is_nan() {
        return x + x;
    }
    if x == 0. {
        return f32::NEG_INFINITY;
    }
    if x < 0. {
        return f32::NAN;
    }
    if x == f32::INFINITY {
        return x;
    }
    let mut bits = x.to_bits();
    let mut expo = ((bits >> 23) as i32) - 127;
    if expo == -127 {
        let y = f32::from_bits((bits & 0x007fffff) | 0x3f800000) - 1.;
        bits = y.to_bits();
        expo = ((bits >> 23) as i32) - 253;
    }
    if (x - 1.).abs() < f32::from_bits(0x3d800000) {
        let r = x - 1.;
        let u = r / (2. + r);
        let correction = r * u;
        let v = u + u;
        let v2 = v * v;
        let v3 = v * v2;
        let q = v2
            .mul_add(f32::from_bits(0x3c4ccccd), f32::from_bits(0x3daaaaab))
            .mul_add(v3, -correction);
        let hi = f32::from_bits(r.to_bits() & 0xffff0000);
        let lo = r - hi;
        let f = q + lo;
        return (f.mul_add(f32::from_bits(0x3a37b152), hi * f32::from_bits(0x3a37b152))
            + f * f32::from_bits(0x3ede0000))
            + hi * f32::from_bits(0x3ede0000);
    }
    let m = (bits & 0x007f0000) + ((bits & 0x00008000) << 1);
    let index = (m >> 16) as usize;
    let y = f32::from_bits((bits & 0x007fffff) | 0x3f000000);
    let f = f32::from_bits(m | 0x3f000000);
    let r = (f - y) * f32::from_bits(INV[index]);
    let q = f32::from_bits(0x3eaaaaab).mul_add(r, 0.5).mul_add(r * r, r);
    let tail = f32::from_bits(0x39826a13).mul_add(expo as f32, -(q * f32::from_bits(0x3ede5bd9)))
        + f32::from_bits(TAIL[index]);
    let head = f32::from_bits(0x3e9a0000).mul_add(expo as f32, f32::from_bits(HEAD[index]));
    head + tail
}

