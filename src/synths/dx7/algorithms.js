/** Who modulates whom in an algorithm (0-based, 0–31): operators are numbered 1–6 as on the panel. */
export function algorithmGraph(index){
 const alg=ALGORITHMS[Math.max(0,Math.min(31,index))];
 let sources=[[],[],[]];
 const edges=[],carriers=[],feedback=[];
 for(let i=0;i<6;i++){
  const flags=alg[i],op=6-i,inBus=flags>>4&3,outBus=flags&3,add=!!(flags&4);
  if(inBus&&sources[inBus].length)for(const s of sources[inBus])edges.push([s,op]);
  if((flags&0xc0)===0xc0)feedback.push(op);
  if(outBus===0)carriers.push(op);else if(add)sources[outBus].push(op);else sources[outBus]=[op];
 }
 // depth: carriers at 0, a modulator one step above the highest thing it modulates
 const depth={};
 const level=op=>depth[op]??=edges.filter(([f])=>f===op).reduce((m,[,t])=>Math.max(m,level(t)+1),0);
 for(let op=1;op<=6;op++)level(op);
 return {edges,carriers,feedback,depth};
}
