// Counts how often each instrument in the picker is used by the presets, and lists the dead ones: nothing plays them. Counts a preset once per role it fills,
// and keeps visible presets apart from hidden ones, since an instrument only hidden presets use is one nobody hears any more.
//   npx vite-node tools/inventoryInstruments.mjs       writes docs/INSTRUMENT_INVENTORY.md and prints a summary
import { readFileSync, writeFileSync } from 'node:fs';
import { WASM_PRESETS } from '../src/synth-lab/voiceLibrary';

const read = (path) => JSON.parse(readFileSync(path, 'utf8'));
const library = read('src/library/scenes.json'), voices = read('src/library/voices.json'), classics = read('src/library/classics.json');
const presetsSource = readFileSync('src/app/presets.js', 'utf8'), rolesSource = /ROLE_PRESETS = (\{[^}]*\})/.exec(presetsSource)?.[1] ?? '{}';
const hiddenSource = /HIDDEN_PRESETS = new Set\(\[([^\]]*)\]/.exec(presetsSource)?.[1] ?? '';
const pickerHidden = new Set([...hiddenSource.matchAll(/'([^']+)'/g)].map((m) => m[1]));
const roleDefaults = new Set([...rolesSource.matchAll(/'([^']+)'/g)].map((m) => m[1]));

const instruments = new Map();
for (const [category, entries] of Object.entries(voices)) for (const name of Object.keys(entries)) instruments.set(name, { name, category, visible: 0, hidden: 0, roles: {}, scenes: [] });
for (const name of Object.keys(WASM_PRESETS)) instruments.set(name, { name, category: 'Wasm voices', visible: 0, hidden: 0, roles: {}, scenes: [] });
for (const { synth, name } of classics.sounds) { const label = `${classics.synths[synth]} · ${name}`; instruments.set(label, { name: label, category: 'Classic synths', visible: 0, hidden: 0, roles: {}, scenes: [] }); }

const unknown = new Map();
const nameOf = (spec) => (typeof spec === 'string' ? spec : spec?.name ?? null);
for (const scene of library.scenes) {
    const seen = [...Object.entries(scene.voices ?? {}), ...Object.entries(scene.layerVoices ?? {})];
    const counted = new Set();
    for (const [role, spec] of seen) {
        const name = nameOf(spec);
        if (!name || counted.has(`${role}:${name}`)) continue;
        counted.add(`${role}:${name}`);
        const entry = instruments.get(name);
        if (!entry) { if (typeof spec === 'string') unknown.set(name, (unknown.get(name) ?? 0) + 1); continue; }
        entry[scene.hidden ? 'hidden' : 'visible']++;
        entry.roles[role] = (entry.roles[role] ?? 0) + 1;
        if (!scene.hidden) entry.scenes.push(scene.name);
    }
}

const list = [...instruments.values()], total = (e) => e.visible + e.hidden;
const isDead = (e) => total(e) === 0 && !roleDefaults.has(e.name);
const dead = list.filter(isDead), hiddenOnly = list.filter((e) => e.visible === 0 && e.hidden > 0), once = list.filter((e) => e.visible === 1);
const row = (e) => `| ${e.name} | ${e.category} | ${e.visible} | ${e.hidden} | ${Object.entries(e.roles).sort((a, b) => b[1] - a[1]).map(([r, n]) => `${r} ${n}`).join(', ') || '-'} | ${[pickerHidden.has(e.name) ? 'hidden from pickers' : '', roleDefaults.has(e.name) ? 'role default' : ''].filter(Boolean).join(', ') || ''} |`;
const table = (rows) => ['| Instrument | Category | Visible presets | Hidden presets | Roles | Notes |', '|---|---|---:|---:|---|---|', ...rows.map(row)];
const sorted = [...list].sort((a, b) => b.visible - a.visible || b.hidden - a.hidden || a.name.localeCompare(b.name));
const byCategory = Object.entries(Object.groupBy(list, (e) => e.category)).map(([category, entries]) => `| ${category} | ${entries.length} | ${entries.filter(isDead).length} | ${entries.filter((e) => e.visible === 0 && e.hidden > 0).length} | ${entries.reduce((sum, e) => sum + e.visible, 0)} |`);

const lines = ['# Instrument inventory', '', 'Generated by `tools/inventoryInstruments.mjs`; do not edit by hand. A preset counts once per role an instrument fills, its layer voices included. Instruments that only a share link or a person at the picker could reach still count as dead here.', '',
    `${list.length} instruments, ${library.scenes.filter((s) => !s.hidden).length} visible presets, ${library.scenes.filter((s) => s.hidden).length} hidden presets.`, '',
    '| Category | Instruments | Dead | Hidden presets only | Uses in visible presets |', '|---|---:|---:|---:|---:|', ...byCategory, '',
    `## Dead: no preset uses them (${dead.length})`, '', ...table(dead), '',
    `## Heard only in hidden presets (${hiddenOnly.length})`, '', ...table(hiddenOnly), '',
    `## Used by one visible preset (${once.length})`, '', ...table(once), '',
    '## Everything, most used first', '', ...table(sorted), ''];
if (unknown.size) lines.splice(lines.indexOf('## Everything, most used first'), 0, `## Named by presets but not in the list (${unknown.size})`, '', ...[...unknown].map(([name, n]) => `- ${name}: ${n}`), '');
writeFileSync('docs/INSTRUMENT_INVENTORY.md', lines.join('\n'));

console.log(`${list.length} instruments; ${dead.length} dead, ${hiddenOnly.length} hidden presets only, ${once.length} used once`);
console.log('by category:\n' + byCategory.join('\n'));
console.log('dead:', dead.map((e) => e.name).join(', '));
console.log('hidden only:', hiddenOnly.map((e) => e.name).join(', '));
console.log('unknown:', [...unknown].map(([n, c]) => `${n} ${c}`).join(', ') || 'none');
console.log('top 12:', sorted.slice(0, 12).map((e) => `${e.name} ${e.visible}`).join(', '));
console.log('Measured:', list.filter((e) => e.category === 'Measured').map((e) => `${e.name} ${e.visible}/${e.hidden}`).join(', '));
