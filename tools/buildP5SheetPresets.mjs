// Builds src/synths/prophet/sheetPresets.js from the measured patch sheets
// (banks/prophet-5/patch-sheets.json, made by tools/p5-patch-sheets). Each sheet becomes an
// Oracle 5 sound of our own: approximated panel values from the drawing, a new name, a place in
// the synth's categories and a matched level. Run with npx vite-node tools/buildP5SheetPresets.mjs.
import fs from 'node:fs';
import {toPairs,sanitize} from '../src/synths/prophet/params.js';
import {sheetEngineValues} from '../src/synths/prophet/sheets.js';
import {MODELS} from '../src/synths/engine/offline.js';
import {levelVolume} from './levelMatch.mjs';

// sheet code → [our name, category, styles]
const SOUNDS={
 11:['Bold Brass','brass',['fat']],12:['Deep Strings','strings',['low','pwm']],13:['Damped Clav','keys',['percussive']],14:['Struck Tines','keys',['tine','percussive']],
 15:['Airy Flutes','voices',['breathy']],16:['Plucked Court','keys',['plucked','bright']],17:['Sync Edge','lead',['sync']],18:['Pop Organ','organ',['percussive']],
 21:['Gliding Unison','lead',['unison','glide','resonant']],22:['Pump Organ','organ',['reedy']],23:['Nasal Organ','organ',['resonant']],24:['Tin Piano','keys',['toy','bright']],
 25:['Horn & Pipe','brass',['layered']],26:['Wah Pulse','motion',['filter']],27:['Reedy Organ','organ',['reedy']],28:['Fifth Brass','brass',['fifths']],
 31:['Chiff Pipes','organ',['chiff']],32:['Sync Growl','lead',['sync','gritty']],33:['Warm Tines','keys',['tine','warm']],34:['Bright Strings','strings',['bright']],
 35:['Octave Saws','lead',['octaves']],36:['Echo Tail','motion',['echo']],37:['Late Harmonic','lead',['vibrato']],38:['Bouncing Echo','motion',['echo','rhythmic']],
 41:['Breathing Pulse','strings',['pwm','soft']],42:['Drifting Sync','motion',['sync','slow']],43:['Resonant Fourths','lead',['fourths','resonant']],44:['Harmonic Sweep','motion',['sweep']],
 45:['Creeping Sync','motion',['sync','slow']],46:['Random Steps','motion',['random','arpeggio']],47:['Saw Steps','motion',['arpeggio']],48:['Clanging Bells','bells',['metallic']],
 51:['Visitor','fx',['cosmic']],52:['Noise Wash','fx',['noise','sweep']],53:['Falling Bells','bells',['descending']],54:['Falling Pulse','motion',['descending','pwm']],
 55:['Rotor Blades','fx',['rhythmic','noise']],56:['Ringing Bells','bells',['resonant']],
};
const COLOURS={lead:'#d9534f',bells:'#8f7fd1',keys:'#e0a526',strings:'#5b8fd9',brass:'#c8792b',organ:'#7fb36a',bass:'#2f7a6d',fx:'#8a8f96',voices:'#c25b8f',motion:'#4fb3c2'};

const voiced=(panel,volume)=>sanitize({...sheetEngineValues(panel),reverbMix:.15,volume});
const sheets=JSON.parse(fs.readFileSync('banks/prophet-5/patch-sheets.json','utf8'));
const rows=sheets.patches.map(p=>{
 const [name,category,styles]=SOUNDS[p.code]??(()=>{throw Error('No name for sheet '+p.code);})();
 const volume=levelVolume(MODELS.prophet5,v=>toPairs(voiced(p.values,v)),voiced(p.values,undefined).volume);
 return ` {name:${JSON.stringify(name)},category:'${category}',styles:${JSON.stringify(styles)},colour:'${COLOURS[category]}',volume:${volume},panel:${JSON.stringify(p.values)}},`;
});
const names=rows.map(r=>JSON.parse(r.match(/name:("[^"]*")/)[1]));
if(new Set(names).size!==names.length)throw Error('Duplicate names.');
fs.writeFileSync('src/synths/prophet/sheetPresets.js',`// Generated by tools/buildP5SheetPresets.mjs; do not edit by hand.
// Sounds of our own, approximated from the panel drawings of the original patch sheets (measured
// by tools/p5-patch-sheets: knobs to ±0.05, oscillator pitch to the semitone), renamed and sorted
// into this synth's categories. Panel values use sysex.js's decodeProgram shape (see sheets.js).
export const SHEET_SOUNDS=[
${rows.join('\n')}
];
`);
console.log(`Wrote ${rows.length} sheet sounds.`);
