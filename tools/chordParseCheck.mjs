// How well the chord menu reads the generator's own chord parts: every pad and rhythm part of the captured note database is captured
// as the sequencer captures it, read back into chord-menu settings or called a note line, and counted. Every chord it keeps replays
// exactly the notes it was read from (chordParse.js checks that), so the counts are about how much stays editable as settings.
// Run with: npx vite-node tools/chordParseCheck.mjs
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';
import { createGunzip } from 'node:zlib';
import { capturePattern } from '../src/seq/capture';
import { makeKey } from '../src/seq/harmony';
import { parsePattern } from '../src/synths/all/chordParse';

const input = path.resolve('reports/survey_generator/data/notes.jsonl.gz');
const stats = { pad: {}, rhythm: {} };
const add = (object, key) => { object[key] = (object[key] ?? 0) + 1; };
const examples = {};
const masks = {};
const stream = readline.createInterface({ input: fs.createReadStream(input).pipe(createGunzip()), crlfDelay: Infinity });
let presets = 0;
for await (const text of stream) {
    if (!text) continue;
    const r = JSON.parse(text), s = r.settings;
    if (s.playMusic === false || s.tonality?.mode === 'atonal') continue;
    presets++;
    const key = makeKey(r.bars[0].music.mode, r.bars[0].music.tonic), stepsPerBar = r.bars[0].meter.units * 4;
    if (r.bars.some(b => b.meter.units * 4 !== stepsPerBar)) continue; // a captured song has one bar length
    const records = r.bars.map(b => ({ ...b, events: b.events.filter(e => !s.muted?.[e.role]) }));
    for (const role of ['pad', 'rhythm']) {
        const pattern = capturePattern(records, role, { key, stepsPerBar });
        const S = stats[role];
        for (const g of parsePattern(pattern, key, stepsPerBar)) {
            add(S, 'parts');
            if (g.kind === 'line') { add(S, 'line'); add(S, `line: ${g.reason}`); continue; }
            add(S, 'chord');
            add(S, g.chord.voicing ? 'voicing kept exactly (grey chord fields)' : 'voicing as settings');
            add(S, g.chord.strikes ? 'strikes kept exactly (grey play fields)' : 'play as settings');
            add(S, `style: ${g.style}`);
            if (!g.chord.voicing && !g.chord.strikes) add(S, 'fully settings');
            if (g.chord.mask) { masks[g.chord.mask.length] ??= {}; add(masks[g.chord.mask.length], g.chord.mask); }
            if (g.chord.voicing && !examples.voicing) examples.voicing = { preset: r.name, chord: g.chord, notes: g.notes };
            if (g.chord.strikes && !examples.strikes) examples.strikes = { preset: r.name, chord: g.chord, notes: g.notes };
        }
    }
}
const pct = (a, b) => b ? `${(100 * a / b).toFixed(1)}%` : '—';
for (const role of ['pad', 'rhythm']) {
    const S = stats[role];
    console.log(`\n${role}: ${S.parts} parts (${presets} presets)`);
    for (const [k, v] of Object.entries(S).sort((a, b) => b[1] - a[1])) console.log(`  ${k}: ${v} (${pct(v, S.parts)})`);
}
if (process.env.WRITE_PATTERNS) {
    // the rate flavours the chord menu offers: the commonest hit masks at each cycle length (steps per bar / rate)
    const table = Object.fromEntries(Object.entries(masks).map(([n, counts]) => [n, Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 10).map(([m]) => m)]));
    fs.writeFileSync(path.resolve('src/synths/all/ratePatterns.js'), `// Generated by tools/chordParseCheck.mjs (WRITE_PATTERNS=1) from the generator's own chord parts: the commonest hit masks at each cycle length
// (steps in the bar divided by the rate), 'x' strikes and '.' rests. The chord menu's rate flavour scrolls through the ones that fit.
export const RATE_PATTERNS = ${JSON.stringify(table, null, 1)};
`);
}
if (process.env.EXAMPLES) console.log(JSON.stringify(examples, null, 1).slice(0, 3000));
