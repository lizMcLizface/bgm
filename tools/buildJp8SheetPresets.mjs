const COLOURS={lead:'#d9534f',bells:'#8f7fd1',keys:'#e0a526',strings:'#5b8fd9',brass:'#c8792b',organ:'#7fb36a',bass:'#2f7a6d',fx:'#8a8f96',voices:'#c25b8f',motion:'#4fb3c2'};

// Level matching: each sound's volume is set so a held four-note chord sits near the hand-made
// sounds (about -23 dB RMS), moving at most 12 dB and never clipping. presets.js builds the same values.
const TARGET_DB=-23,ASSIGN={solo:0,unison:1,poly1:2,poly2:3};
const voiced=(panel,volume)=>sanitize({...engineValues(panel),assign:ASSIGN[panel.assign],reverbMix:.15,volume});
const level=panel=>levelVolume(MODELS.jupiter8,v=>toPairs(voiced(panel,v)),voiced(panel,undefined).volume,TARGET_DB);
const sheets=JSON.parse(fs.readFileSync('banks/jupiter-8/patch-sheets.json','utf8'));
if(sheets.patches.length!==Object.keys(SOUNDS).length)throw Error('Expected one sheet per sound.');
const rows=sheets.patches.map(p=>{
 const [name,category,styles]=SOUNDS[p.code]??(()=>{throw Error('No name for sheet '+p.code);})();
 return ` {name:${JSON.stringify(name)},category:'${category}',styles:${JSON.stringify(styles)},colour:'${COLOURS[category]}',volume:${level(p.values)},panel:${JSON.stringify(p.values)}},`;
});
const names=rows.map(r=>JSON.parse(r.match(/name:("[^"]*")/)[1]));
if(new Set(names).size!==names.length)throw Error('Duplicate names.');
fs.writeFileSync('src/synths/jupiter/sheetPresets.js',`// Generated by tools/buildJp8SheetPresets.mjs; do not edit by hand.
// Sounds of our own, approximated from the panel drawings of the factory patch sheets
// (measured by tools/jp8-patch-sheets: sliders and knobs to ±0.05, pitch to the semitone),
// renamed and sorted into this synth's categories. Panel values use patch.js's decodePatch shape.
export const SHEET_SOUNDS=[
${rows.join('\n')}
];
`);
console.log(`Wrote ${rows.length} sheet sounds.`);
